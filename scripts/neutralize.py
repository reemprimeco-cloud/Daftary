def neutralize(path, dry=True):
    src = open(path, encoding="utf-8").read()
    out, changed, in_block = [], 0, False
    for line in src.split("\n"):
        t = line.lstrip()
        # سطر تعليق كامل — يُترك
        if in_block or t.startswith("//") or t.startswith("*") or t.startswith("/*"):
            if t.startswith("/*") and "*/" not in t:
                in_block = True
            if in_block and "*/" in t:
                in_block = False
            out.append(line); continue
        new = line
        for a, b in MAP:
            new = re.sub(r"(?<![\u0621-\u064A])([وفبلس]?)" + a + r"(?![\u0621-\u064A])", lambda m, b=b: m.group(1) + b, new)
        if new != line:
            changed += 1
            if dry:
                print(f"  - {line.strip()[:110]}")
                print(f"  + {new.strip()[:110]}")
        out.append(new)
    if not dry:
        open(path, "w", encoding="utf-8").write("\n".join(out))
    return changed

if __name__ == "__main__":
    dry = "--apply" not in sys.argv
    total = 0
    for f in sys.argv[1:]:
        if f == "--apply": continue
        n = neutralize(f, dry)
        print(f"{f}: {n} سطراً")
        total += n
    print(f"\nالمجموع: {total} سطراً")
