"use client";

import { useEffect, useState } from "react";
import { isNativeApp } from "@/lib/native";

// شروط الدفع بالبطاقة — تخص مستخدمات الموقع وحدهن.
//
// ما نعرضها داخل التطبيق إطلاقاً: بند آبل 3.1.1 يمنع توجيه مستخدم التطبيق
// لوسيلة شراء خارج المتجر، وصفحة الشروط مفتوحة من داخل التطبيق نفسه. نفس
// المنطق المطبَّق بشاشة الاشتراك (الدفع بالبطاقة ما يظهر إلا للويب).
//
// العرض بعد التحميل مو بالخادم: الخادم ما يعرف هل الطلب من التطبيق ولا من
// المتصفح (التطبيق يحمّل نفس الموقع بلا ترويسة مميزة)، فلو رسمناها بالخادم
// راحت تطلع داخل التطبيق كذلك. isNativeApp تُفحص بالمتصفح وحده.
export default function WebPaymentTerms() {
  const [show, setShow] = useState(false);

  useEffect(() => {
    if (process.env.NEXT_PUBLIC_ENABLE_WEB_PAYMENTS !== "true") return;
    setShow(!isNativeApp());
  }, []);

  if (!show) return null;

  return (
    <section style={{ marginBottom: 26 }}>
      <h2 style={{ color: "#5C4B8C", fontSize: 17.5, fontWeight: 800, margin: "0 0 8px" }}>الدفع من الموقع الإلكتروني</h2>
      <p style={p}>
        إذا اشتركتِ من موقع دفتري على المتصفح، يتم الدفع بالبطاقة (كي نت أو فيزا/ماستركارد) عبر بوابة الدفع
        {" "}<strong>Tap</strong>، وتنطبق عليك البنود التالية بدل بنود متجر آبل أعلاه:
      </p>
      <ul style={ul}>
        <li style={li}>
          <strong>شراء لسنة دراسية واحدة بدون تجديد تلقائي.</strong> لا يُخصم منك أي مبلغ بعد ذلك من تلقاء نفسه،
          ويبقى اشتراكك سارياً حتى تاريخ انتهائه المعروض داخل حسابك، وتجدّدينه بنفسك وقت ما تحبّين.
        </li>
        <li style={li}>
          دفتري من إنتاج <strong>شركة برايم للطباعة</strong>، ويظهر اسم <strong>Prime Printing</strong> على صفحة
          الدفع وفي كشف حسابك البنكي.
        </li>
        <li style={li}>
          بيانات بطاقتك تُدخل مباشرة في صفحة Tap الآمنة — نحن لا نستقبلها ولا نخزّنها ولا نطّلع عليها،
          ولا يصلنا من العملية إلا رقمها ومبلغها وحالتها.
        </li>
        <li style={li}>
          لترقية باقتك لعدد أبناء أكبر، تشترين الباقة الأكبر من صفحة الاشتراك، وتحلّ محل باقتك الحالية.
        </li>
        <li style={li}>
          <strong>الاسترجاع:</strong> طلبات استرجاع المدفوعات التي تمت عبر الموقع تُرسل إلينا مباشرة على البريد
          أدناه — لا عبر آبل — وتُدرس كل حالة على حدة.
        </li>
      </ul>
    </section>
  );
}

const p = { margin: "0 0 10px" };
const ul = { margin: "0 0 10px", paddingInlineStart: 22 };
const li = { marginBottom: 6 };
